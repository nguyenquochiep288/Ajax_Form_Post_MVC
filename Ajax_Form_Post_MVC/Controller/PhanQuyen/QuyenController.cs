		public ActionResult Index(int Page = 1, string SearchString = "", string ShowSearchValue = "")
		{
			try
			{
				if (Utility.KiemTra())
				{
					return RedirectToAction("Index", "Admin");
				}
				if (!Utility.KiemTraQuyen("Quyen", "View"))
				{
					base.TempData["TitleError"] = "Bạn không có quyền truy cập chức năng!";
					return RedirectToAction("Index", "Notfound");
				}
				ShowSearchValue = Utility.GetShowSearchValue<web_Quyen>(ShowSearchValue);
				ApiResponse listData = Utility.GetListData<v_v_web_Quyen>("Quyen", ShowSearchValue, SearchString, Utility.LOC_ID);
				if (!listData.Success)
				{
					base.TempData["TitleError"] = listData.Message;
					return RedirectToAction("Index", "Notfound");
				}
				IPagedList<v_v_web_Quyen> iPagedList = (listData.Data as List<v_v_web_Quyen>).OrderBy((v_v_web_Quyen s) => s.ID_MENU).ToPagedList(Page, Utility.GetPageSize());
