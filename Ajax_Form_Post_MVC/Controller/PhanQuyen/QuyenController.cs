				v_v_web_Quyen2.IPagedList = iPagedList;
				v_v_web_Quyen2.lstweb_Menu = Utility.GetListData<v_web_Menu>("Menu").Data as List<v_web_Menu>;
				base.ViewBag.searchValue = SearchString;
				base.ViewBag.showsearchValue = ShowSearchValue;
				base.ViewBag.PermissionEdit = Utility.KiemTraQuyen("Quyen", "Edit");
				base.ViewBag.PermissionDelete = Utility.KiemTraQuyen("Quyen", "Delete");
				base.ViewBag.PermissionCreate = Utility.KiemTraQuyen("Quyen", "Create");
				return View(v_v_web_Quyen2);
			}
			catch (Exception ex)
			{
				Utility.WriteLog(this, MethodBase.GetCurrentMethod().Name, ex);
				base.TempData["TitleError"] = "Đã có lỗi phát sinh trong phiên làm việc!";
				base.TempData["DetailError"] = ex.Message;
				return RedirectToAction("Index", "Notfound");
