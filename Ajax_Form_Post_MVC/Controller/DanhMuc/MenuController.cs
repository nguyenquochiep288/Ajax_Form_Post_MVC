		public ActionResult Index(int Page = 1, string SearchString = "", string ShowSearchValue = "")
		{
			try
			{
				if (Utility.KiemTra())
				{
					return RedirectToAction("Index", "Admin");
				}
				if (!Utility.KiemTraQuyen("Menu", "View"))
				{
					base.TempData["TitleError"] = "Bạn không có quyền truy cập chức năng!";
					return RedirectToAction("Index", "Notfound");
				}
				ShowSearchValue = Utility.GetShowSearchValue<web_Menu>(ShowSearchValue);
				ApiResponse listData = Utility.GetListData<v_web_Menu>("Menu", ShowSearchValue, SearchString);
				if (!listData.Success)
				{
					base.TempData["TitleError"] = listData.Message;
					return RedirectToAction("Index", "Notfound");
				}
				List<v_web_Menu> list = listData.Data as List<v_web_Menu>;
				foreach (v_web_Menu item in list)
				{
					item.NAME_ORDERBY = item.NAME_ORDERBY + item.NAME_QUYENCHA + item.NAME;
				}
				IPagedList<v_web_Menu> iPagedList = list.OrderBy((v_web_Menu e) => e.NAME_ORDERBY).ToPagedList(Page, Utility.GetPageSize());
				v_v_web_Menu v_v_web_Menu2 = new v_v_web_Menu();
				v_v_web_Menu2.IPagedList = iPagedList;
				v_v_web_Menu2.lstweb_Menu = new List<v_web_Menu>();
				v_v_web_Menu2.lstweb_Menu = list.OrderBy((v_web_Menu e) => e.NAME_ORDERBY).ToList();
				base.ViewBag.searchValue = SearchString;
				base.ViewBag.showsearchValue = ShowSearchValue;
				base.ViewBag.PermissionEdit = Utility.KiemTraQuyen("Menu", "Edit");
				base.ViewBag.PermissionDelete = Utility.KiemTraQuyen("Menu", "Delete");
				base.ViewBag.PermissionCreate = Utility.KiemTraQuyen("Menu", "Create");
				return View(v_v_web_Menu2);
			}
			catch (Exception ex)
			{
				Utility.WriteLog(this, MethodBase.GetCurrentMethod().Name, ex);
				base.TempData["TitleError"] = "Đã có lỗi phát sinh trong phiên làm việc!";
				base.TempData["DetailError"] = ex.Message;
				return RedirectToAction("Index", "Notfound");
			}
		}

