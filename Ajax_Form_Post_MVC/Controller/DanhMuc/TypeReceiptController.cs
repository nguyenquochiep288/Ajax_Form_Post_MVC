		public ActionResult Index(int Page = 1, string SearchString = "", string ShowSearchValue = "")
		{
			try
			{
				if (Utility.KiemTra())
				{
					return RedirectToAction("Index", "Admin");
				}
				if (!Utility.KiemTraQuyen("TypeReceipt", "View"))
				{
					base.TempData["TitleError"] = "Bạn không có quyền truy cập chức năng!";
					return RedirectToAction("Index", "Notfound");
				}
				ShowSearchValue = Utility.GetShowSearchValue<dm_LoaiPhieuThu>(ShowSearchValue);
				ApiResponse listData = Utility.GetListData<v_dm_LoaiPhieuThu>("TypeReceipt", ShowSearchValue, SearchString, Utility.LOC_ID);
				if (!listData.Success)
				{
					base.TempData["TitleError"] = listData.Message;
					return RedirectToAction("Index", "Notfound");
				}
				IPagedList<v_dm_LoaiPhieuThu> iPagedList = (listData.Data as List<v_dm_LoaiPhieuThu>).ToPagedList(Page, Utility.GetPageSize());
