				v_v_dm_LoaiPhieuThu2.IPagedList = iPagedList;
				base.ViewBag.searchValue = SearchString;
				base.ViewBag.showsearchValue = ShowSearchValue;
				base.ViewBag.PermissionEdit = Utility.KiemTraQuyen("TypeReceipt", "Edit");
				base.ViewBag.PermissionDelete = Utility.KiemTraQuyen("TypeReceipt", "Delete");
				base.ViewBag.PermissionCreate = Utility.KiemTraQuyen("TypeReceipt", "Create");
				return View(v_v_dm_LoaiPhieuThu2);
			}
			catch (Exception ex)
			{
				Utility.WriteLog(this, MethodBase.GetCurrentMethod().Name, ex);
				base.TempData["TitleError"] = "Đã có lỗi phát sinh trong phiên làm việc!";
				base.TempData["DetailError"] = ex.Message;
