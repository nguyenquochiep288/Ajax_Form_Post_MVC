        // GET: Parameter
        public ActionResult Index(int Page = 1, string SearchString = "", string ShowSearchValue = "")
        {
            try
            {
                if (Utility.KiemTra())
                {
                    return RedirectToAction("Index", "Admin");
                }
                if (!Utility.KiemTraQuyen(API.web_Parameter, API.Xem))
                {
                    TempData["TitleError"] = API.TitlePermission;
                    return RedirectToAction("Index", "Notfound");
                }
                ShowSearchValue = Utility.GetShowSearchValue<web_Parameter>(ShowSearchValue);
                var apiResponse = Utility.GetListData<v_web_Parameter>(API.web_Parameter, ShowSearchValue, SearchString, "");
                if (!apiResponse.Success)
                {
                    TempData["TitleError"] = apiResponse.Message;
                    return RedirectToAction("Index", "Notfound");
                }
                IPagedList<v_web_Parameter> lstpage = (apiResponse.Data as List<v_web_Parameter>).ToPagedList(Page, Utility.GetPageSize());

                v_v_web_Parameter web_Parameter = new v_v_web_Parameter();
                web_Parameter.IPagedList = lstpage;
                //@LSTKHOAINGOAI

                ViewBag.searchValue = SearchString;
                ViewBag.showsearchValue = ShowSearchValue;

                ViewBag.PermissionEdit = Utility.KiemTraQuyen(API.web_Parameter, API.Edit);
                ViewBag.PermissionDelete = Utility.KiemTraQuyen(API.web_Parameter, API.Delete);
                ViewBag.PermissionCreate = Utility.KiemTraQuyen(API.web_Parameter, API.Create);
                return View(web_Parameter);
            }
            catch (Exception ex)
            {
                Utility.WriteLog(this, MethodBase.GetCurrentMethod().Name, ex);
                TempData["TitleError"] = API.TitleTryCatch;
                TempData["DetailError"] = ex.Message;
                return RedirectToAction("Index", "Notfound");
            }
        }

