        public ActionResult Index(int Page = 1, string SearchString = "", string ShowSearchValue = "")
        {
            try
            {
                if (Utility.KiemTra())
                {
                    return RedirectToAction("Index", "Admin");
                }
                if (!Utility.KiemTraQuyen(API.dm_KhuVuc, API.Xem))
                {
                    TempData["TitleError"] = API.TitlePermission;
                    return RedirectToAction("Index", "Notfound");
                }
                ShowSearchValue = Utility.GetShowSearchValue<dm_KhuVuc>(ShowSearchValue);
                var apiResponse = Utility.GetListData<v_dm_KhuVuc>(API.dm_KhuVuc, ShowSearchValue, SearchString, Utility.LOC_ID);
                if (!apiResponse.Success)
                {
                    TempData["TitleError"] = apiResponse.Message;
                    return RedirectToAction("Index", "Notfound");
                }
                IPagedList<v_dm_KhuVuc> lstpage = (apiResponse.Data as List<v_dm_KhuVuc>).ToPagedList(Page, Utility.GetPageSize());

                v_v_dm_KhuVuc dm_KhuVuc = new v_v_dm_KhuVuc();
                dm_KhuVuc.IPagedList = lstpage;
                //@LSTKHOAINGOAI

                ViewBag.searchValue = SearchString;
                ViewBag.showsearchValue = ShowSearchValue;

                ViewBag.PermissionEdit = Utility.KiemTraQuyen(API.dm_KhuVuc, API.Edit);
                ViewBag.PermissionDelete = Utility.KiemTraQuyen(API.dm_KhuVuc, API.Delete);
                ViewBag.PermissionCreate = Utility.KiemTraQuyen(API.dm_KhuVuc, API.Create);
                return View(dm_KhuVuc);
            }
            catch (Exception ex)
            {
                Utility.WriteLog(this, MethodBase.GetCurrentMethod().Name, ex);
                TempData["TitleError"] = API.TitleTryCatch;
                TempData["DetailError"] = ex.Message;
                return RedirectToAction("Index", "Notfound");
            }
        }

